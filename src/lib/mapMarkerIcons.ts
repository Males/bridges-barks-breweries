export type MapMarkerType = 'start' | 'bridge' | 'venue'

const DEFAULT_SIZE = 32

/** Build HTML for a marker: circle with homepage colour + SVG icon inside */
export function getMarkerHtml(
  type: MapMarkerType,
  size: number = DEFAULT_SIZE
): string {
  const border = '2px solid #1A1344'
  const boxShadow = '0 2px 4px rgba(0,0,0,0.2)'

  if (type === 'start') {
    // Pin icon (from directions) on green circle
    const pinSvg = getMapPinSvg(COLORS.white)
    return `<div style="
      width:${size}px;height:${size}px;
      background:${COLORS.start};
      border:${border};
      border-radius:50%;
      display:flex;align-items:center;justify-content:center;
      box-shadow:${boxShadow};
    "><svg width="${size * 0.6}" height="${size * 0.6}" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">${pinSvg}</svg></div>`
  }

  if (type === 'bridge') {
    // Bridge SVG in white on cobalt circle
    const paths = `<path d="${BRIDGE_PATH}" fill="${COLORS.white}"/>`
    return `<div style="
      width:${size}px;height:${size}px;
      background:${COLORS.bridge};
      border:${border};
      border-radius:50%;
      display:flex;align-items:center;justify-content:center;
      box-shadow:${boxShadow};
    "><svg width="${size * 0.55}" height="${size * 0.55}" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">${paths}</svg></div>`
  }

  // venue: beer SVG in navy on golden circle
  const paths = BEER_PATHS.map((d) => `<path d="${d}" fill="${COLORS.navy}"/>`).join('')
  return `<div style="
    width:${size}px;height:${size}px;
    background:${COLORS.venue};
    border:${border};
    border-radius:50%;
    display:flex;align-items:center;justify-content:center;
    box-shadow:${boxShadow};
  "><svg width="${size * 0.55}" height="${size * 0.55}" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">${paths}</svg></div>`
}
